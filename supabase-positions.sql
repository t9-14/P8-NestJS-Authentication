create table if not exists public.positions (
  id bigint generated by default as identity primary key,
  user_id uuid not null references auth.users(id) on delete cascade,
  position_code text not null check (length(btrim(position_code)) > 0),
  position_name text not null check (length(btrim(position_name)) > 0),
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  constraint positions_user_code_unique unique (user_id, position_code)
);

alter table public.positions enable row level security;

grant usage on schema public to authenticated;
grant select, insert, update, delete on table public.positions to authenticated;
grant usage, select on sequence public.positions_id_seq to authenticated;

drop policy if exists "Users can read own positions" on public.positions;
create policy "Users can read own positions" on public.positions
  for select to authenticated using ((select auth.uid()) = user_id);

drop policy if exists "Users can insert own positions" on public.positions;
create policy "Users can insert own positions" on public.positions
  for insert to authenticated with check ((select auth.uid()) = user_id);

drop policy if exists "Users can update own positions" on public.positions;
create policy "Users can update own positions" on public.positions
  for update to authenticated using ((select auth.uid()) = user_id)
  with check ((select auth.uid()) = user_id);

drop policy if exists "Users can delete own positions" on public.positions;
create policy "Users can delete own positions" on public.positions
  for delete to authenticated using ((select auth.uid()) = user_id);
